-- Script de creación de la base de datos GENERALA
-- Ejecutar en SQL Server Management Studio conectado a la instancia local (Data Source=.)

IF DB_ID('GENERALA') IS NULL
    CREATE DATABASE GENERALA;
GO

USE GENERALA;
GO

-- ---------- Tablas ----------

IF OBJECT_ID('dbo.USUARIO', 'U') IS NULL
CREATE TABLE dbo.USUARIO (
    ID       INT IDENTITY(1,1) PRIMARY KEY,
    USERNAME NVARCHAR(50)  NOT NULL UNIQUE,
    PASSWORD NVARCHAR(100) NOT NULL
);
GO

IF OBJECT_ID('dbo.BITACORA', 'U') IS NULL
CREATE TABLE dbo.BITACORA (
    ID         INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT           NOT NULL REFERENCES dbo.USUARIO(ID),
    FECHA      DATETIME      NOT NULL,
    EVENTO     NVARCHAR(200) NOT NULL
);
GO

IF OBJECT_ID('dbo.PARTIDA', 'U') IS NULL
CREATE TABLE dbo.PARTIDA (
    ID           INT IDENTITY(1,1) PRIMARY KEY,
    JUGADOR1     INT      NOT NULL REFERENCES dbo.USUARIO(ID),
    JUGADOR2     INT      NOT NULL REFERENCES dbo.USUARIO(ID),
    GANADOR      INT      NULL     REFERENCES dbo.USUARIO(ID), -- NULL = empate
    FECHA_INICIO DATETIME NOT NULL,
    FECHA_FIN    DATETIME NOT NULL
);
GO

-- ---------- Usuario ----------

CREATE OR ALTER PROCEDURE dbo.USUARIO_LISTAR
AS
    SELECT ID, USERNAME, PASSWORD FROM dbo.USUARIO ORDER BY USERNAME;
GO

CREATE OR ALTER PROCEDURE dbo.USUARIO_LOGIN
    @usu  NVARCHAR(50),
    @pass NVARCHAR(100)
AS
    SELECT ID, USERNAME, PASSWORD
    FROM dbo.USUARIO
    WHERE USERNAME = @usu AND PASSWORD = @pass;
GO

CREATE OR ALTER PROCEDURE dbo.USUARIO_INSERTAR
    @usu  NVARCHAR(50),
    @pass NVARCHAR(100)
AS
    INSERT INTO dbo.USUARIO (USERNAME, PASSWORD) VALUES (@usu, @pass);
GO

-- ---------- Bitácora ----------

CREATE OR ALTER PROCEDURE dbo.BITACORA_INSERTAR
    @usu    INT,
    @fecha  DATETIME,
    @evento NVARCHAR(200)
AS
    INSERT INTO dbo.BITACORA (ID_USUARIO, FECHA, EVENTO) VALUES (@usu, @fecha, @evento);
GO

CREATE OR ALTER PROCEDURE dbo.BITACORA_LISTAR
AS
    SELECT B.ID, U.ID, U.USERNAME, B.FECHA, B.EVENTO
    FROM dbo.BITACORA B
    INNER JOIN dbo.USUARIO U ON U.ID = B.ID_USUARIO
    ORDER BY B.FECHA DESC, B.ID DESC;
GO

-- ---------- Partida ----------

CREATE OR ALTER PROCEDURE dbo.PARTIDA_INSERTAR
    @jug1    INT,
    @jug2    INT,
    @ganador INT = NULL,
    @inicio  DATETIME,
    @fin     DATETIME
AS
    INSERT INTO dbo.PARTIDA (JUGADOR1, JUGADOR2, GANADOR, FECHA_INICIO, FECHA_FIN)
    VALUES (@jug1, @jug2, @ganador, @inicio, @fin);
GO

CREATE OR ALTER PROCEDURE dbo.PARTIDA_LISTAR_USUARIO
    @usu INT
AS
    SELECT ID, JUGADOR1, JUGADOR2, GANADOR, FECHA_INICIO, FECHA_FIN
    FROM dbo.PARTIDA
    WHERE JUGADOR1 = @usu OR JUGADOR2 = @usu
    ORDER BY FECHA_INICIO DESC;
GO
